// Convert the MIT-licensed Baileys WAM event and global tables into Rust statics.
import {stripTypeScriptTypes} from 'node:module'
import {readFile,writeFile,mkdtemp,rm} from 'node:fs/promises'
import {join,resolve} from 'node:path'
import {tmpdir} from 'node:os'
import {pathToFileURL} from 'node:url'
const upstream=resolve(process.argv[2]??'../Baileys'),temp=await mkdtemp(join(tmpdir(),'baileys-wam-constants-'))
try {
  await writeFile(join(temp,'constants.mjs'),stripTypeScriptTypes(await readFile(join(upstream,'src/WAM/constants.ts'),'utf8')))
  const {WEB_EVENTS,WEB_GLOBALS,FLAG_BYTE,FLAG_GLOBAL,FLAG_EVENT,FLAG_FIELD,FLAG_EXTENDED}=await import(pathToFileURL(join(temp,'constants.mjs')))
  const text=s=>JSON.stringify(s)
  const kind=type=>typeof type==='string'?{integer:'Kind::Integer',boolean:'Kind::Boolean',string:'Kind::Text',number:'Kind::Number',timer:'Kind::Timer'}[type]??(()=>{throw Error('unknown WAM type '+type)})():`Kind::Enum(&[${Object.entries(type).map(([k,v])=>`(${text(k)},${v})`).join(',')}])`
  const lines=['// Generated by scripts/generate-wam-constants.mjs from Baileys src/WAM/constants.ts. Do not edit.','use super::{Event, Global, Kind, Prop};','',
    `pub const FLAG_BYTE: u8 = ${FLAG_BYTE};`,`pub const FLAG_GLOBAL: u8 = ${FLAG_GLOBAL};`,`pub const FLAG_EVENT: u8 = ${FLAG_EVENT};`,`pub const FLAG_FIELD: u8 = ${FLAG_FIELD};`,`pub const FLAG_EXTENDED: u8 = ${FLAG_EXTENDED};`,'',
    '#[rustfmt::skip]','pub static WEB_EVENTS: &[Event] = &[']
  for(const e of WEB_EVENTS){
    const known=new Set(['name','id','props','weight','wamChannel','privateStatsIdInt']);for(const k of Object.keys(e))if(!known.has(k))throw Error('unknown event field '+k)
    lines.push(`    Event { name: ${text(e.name)}, id: ${e.id}, weight: ${e.weight}, wam_channel: ${text(e.wamChannel)}, private_stats_id_int: ${e.privateStatsIdInt===undefined?'None':`Some(${e.privateStatsIdInt})`}, props: &[${Object.entries(e.props).map(([name,[id,type]])=>`Prop { name: ${text(name)}, id: ${id}, kind: ${kind(type)} }`).join(', ')}] },`)
  }
  lines.push('];','','#[rustfmt::skip]','pub static WEB_GLOBALS: &[Global] = &[')
  for(const g of WEB_GLOBALS){
    const known=new Set(['name','id','type','validator','channels']);for(const k of Object.keys(g))if(!known.has(k))throw Error('unknown global field '+k)
    lines.push(`    Global { name: ${text(g.name)}, id: ${g.id}, kind: ${kind(g.type)}, validator: ${g.validator===undefined?'None':`Some(${text(g.validator)})`}, channels: &[${g.channels.map(text).join(', ')}] },`)
  }
  lines.push('];','')
  await writeFile('src/wam/constants.rs',lines.join('\n'))
  console.log(`Generated ${WEB_EVENTS.length} WAM events and ${WEB_GLOBALS.length} globals`)
}finally{await rm(temp,{recursive:true,force:true})}
